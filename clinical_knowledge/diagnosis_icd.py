# Главы МКБ, коды которых считаются симптоматическими/неспецифичными.
_SYMPTOM_CHAPTER_PREFIXES = ("R", "Z")


def normalize_code(code: str) -> str:
    return (code or "").upper().strip().replace(" ", "")


def is_symptom_code(code: str) -> bool:
    """Симптом/фактор-код (главы R, Z) - не должен 'вести' подбор протокола."""
    c = normalize_code(code)
    return bool(c) and c[0] in _SYMPTOM_CHAPTER_PREFIXES


def lookup_disease_icd(text: str) -> list[str]:
    """Возвращает коды болезней по курируемому словарю нозологий (в порядке специфичности)."""
    low = (text or "").lower()
    if not low.strip():
        return []
    out: list[str] = []
    for stem, code in _DIAGNOSIS_ICD_SEED:
        if stem in low and code not in out:
            out.append(code)
    return out


def prioritize_codes(codes: list[str] | None) -> list[str]:
    """Сначала коды болезней, в конце - симптоматические/неспецифичные (R, Z)."""
    disease: list[str] = []
    symptom: list[str] = []
    seen: set[str] = set()
    for raw in codes or []:
        c = normalize_code(str(raw))
        if not c or c in seen:
            continue
        seen.add(c)
        (symptom if is_symptom_code(c) else disease).append(c)
    return disease + symptom


def has_disease_code(codes: list[str] | None) -> bool:
    return any(not is_symptom_code(c) for c in (codes or []))


_RE_WORD = re.compile(r"[а-яёa-z0-9]+", re.I)


def enrich_diagnosis_codes(
    diagnosis_text: str,
    existing_codes: list[str] | None = None,
) -> tuple[list[str], dict]:
    """Дополняет коды диагноза кодом болезни из словаря, демотит симптом-коды.

    Возвращает (codes, meta). codes - упорядоченные (болезни вперёд).
    meta содержит added_from_lexicon и demoted_symptom для прозрачности.
    """
    existing = [normalize_code(str(c)) for c in (existing_codes or []) if c]
    lex = lookup_disease_icd(diagnosis_text)
    added = [c for c in lex if c not in existing]
    combined = existing + added
    ordered = prioritize_codes(combined)
    meta = {
        "added_from_lexicon": added,
        "had_only_symptom_codes": bool(existing) and not has_disease_code(existing),
        "lexicon_matched": bool(lex),
    }
    return ordered, meta
