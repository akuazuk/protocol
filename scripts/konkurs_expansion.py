"""Расширение B2C TAM: госполиклиники РБ, экспорт (РФ) и переносимость ML-корпуса."""
from __future__ import annotations

from konkurs_finance import FIN_Y3, MARKET_KZ_YEAR
from konkurs_scenarios import b2c_protocol_k

# Belstat 2025: посещения врачей (амбулаторно + на дому), млн/год
BELSTAT_AMBULATORY_VISITS_YEAR = 108_400_000

# Базовый план B2C считает конверсию от частного TAM (30 млн КЗ/год)
B2C_TAM_PRIVATE_YEAR = MARKET_KZ_YEAR

# Upside-знаменатель B2C: все амбулаторные обращения (пациент может загрузить полученное заключение)
B2C_TAM_NATIONAL_AMBULATORY_YEAR = BELSTAT_AMBULATORY_VISITS_YEAR

# РФ: оценка амбулаторных обращений для upside (не базовый план)
RU_AMBULATORY_VISITS_YEAR_EST = 550_000_000

# Конверсии для сравнительной таблицы (базовый план = 0,23% от частного TAM)
BASE_B2C_CONV = FIN_Y3["b2c_checks"] / B2C_TAM_PRIVATE_YEAR  # ~0,232%


def _row(denominator_label: str, tam: int, conv: float, note: str) -> tuple[str, str, str, str, str]:
    checks = int(tam * conv)
    rev_k = b2c_protocol_k(checks)
    conv_pct = f"{conv * 100:.2f}%".replace(".", ",")
    checks_s = f"{checks:,}".replace(",", " ")
    return (denominator_label, f"{tam:,}".replace(",", " "), conv_pct, checks_s, str(rev_k))


# Сравнение: тот же % конверсии, разный знаменатель TAM B2C
B2C_TAM_COMPARE_TABLE = [
    _row(
        "Частный сектор (базовый план 2029)",
        B2C_TAM_PRIVATE_YEAR,
        BASE_B2C_CONV,
        "текущий осторожный финплан",
    ),
    _row(
        "Все амбул. посещения РБ (Belstat 2025)",
        B2C_TAM_NATIONAL_AMBULATORY_YEAR,
        BASE_B2C_CONV,
        "гос- + частные поликлиники; тот же % конверсии",
    ),
    _row(
        "Все амбул. посещения РБ",
        B2C_TAM_NATIONAL_AMBULATORY_YEAR,
        0.001,  # 0,10%
        "upside при массовом SEO и сарафане",
    ),
    _row(
        "РФ, амбул. обращения (оценка)",
        RU_AMBULATORY_VISITS_YEAR_EST,
        0.0005,  # 0,05%
        "экспорт B2C 2031+; только открытые КП/приказы",
    ),
]

