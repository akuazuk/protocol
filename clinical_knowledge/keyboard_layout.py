"""Авто-исправление неправильной раскладки клавиатуры в запросах.

Пользователь набирает русский запрос латиницей (забыл переключить раскладку):
`ntvgthfnehf b rfitkm` на физических клавишах ЙЦУКЕН = «температура и кашель».
Модуль конвертирует QWERTY -> ЙЦУКЕН и включает исправление только тогда, когда
результат похож на русский клинический запрос (есть медицинские основы слов).
Так латинские названия препаратов/коды МКБ (`amoxicillin`, `J45`) не ломаются.

Детерминированно, без LLM.
"""
from __future__ import annotations

import re

# Физическая раскладка US QWERTY -> RU ЙЦУКЕН (строчные).
_QWERTY_TO_RU = {
    "q": "й", "w": "ц", "e": "у", "r": "к", "t": "е", "y": "н", "u": "г",
    "i": "ш", "o": "щ", "p": "з", "[": "х", "]": "ъ",
    "a": "ф", "s": "ы", "d": "в", "f": "а", "g": "п", "h": "р", "j": "о",
    "k": "л", "l": "д", ";": "ж", "'": "э",
    "z": "я", "x": "ч", "c": "с", "v": "м", "b": "и", "n": "т", "m": "ь",
    ",": "б", ".": "ю", "/": ".", "`": "ё",
}

_LAYOUT_MAP: dict[str, str] = {}
for _lat, _rus in _QWERTY_TO_RU.items():
    _LAYOUT_MAP[_lat] = _rus
    if _lat.upper() != _lat:  # только буквы имеют верхний регистр; пунктуацию не трогаем
        _LAYOUT_MAP[_lat.upper()] = _rus.upper()

_CYRILLIC = re.compile(r"[а-яёА-ЯЁ]")
_RU_TOKEN = re.compile(r"[а-яё]+")

# Медицинские/клинические основы слов (нормализованные, ё->е, len>=4).
# Достаточно одного совпадения по основе, чтобы считать запрос русским.
_RU_MED_STEMS = frozenset(
    {
        "температ", "лихорад", "кашель", "кашл", "насморк", "чихан", "першен",
        "боль", "боле", "болит", "голов", "живот", "горло", "горл", "тошнот",
        "рвот", "понос", "диаре", "запор", "изжог", "отрыжк", "сыпь", "зуд",
        "одышк", "удушь", "хрип", "мокрот", "слабост", "устал", "давлен",
        "головокруж", "обморок", "судорог", "отек", "кровотеч", "кровь", "моча",
        "стул", "озноб", "потлив", "гной", "ожог", "перелом", "ушиб", "вывих",
        "укус", "аллерг", "зрен", "слух", "сустав", "спин", "поясниц", "грудь",
        "серд", "сердц", "печен", "почк", "желуд", "кишеч", "легк", "горячк",
        "пневмон", "астма", "бронхит", "гастрит", "диабет", "гипертон", "анеми",
        "инфекц", "вирус", "грипп", "ковид", "ангин", "отит", "синусит",
        "цистит", "пиелонефрит", "аппендицит", "инсульт", "инфаркт", "тромбоз",
        "артрит", "артроз", "экзем", "дерматит", "псориаз", "мигрен", "эпилепс",
        "депресс", "тревог", "лечен", "лечит", "препарат", "лекарств", "таблет",
        "антибиотик", "обследован", "анализ", "диагноз", "диагност", "симптом",
        "синдром", "госпитализ", "наблюден", "профилакт", "вакцин", "прививк",
        "беремен", "ребен", "дети", "детск", "взросл", "пациент", "врач",
        "прием", "приём", "жалоб", "недел", "температур", "болезн",
    }
)


def has_cyrillic(text: str | None) -> bool:
    return bool(_CYRILLIC.search(text or ""))


def fix_keyboard_layout(text: str | None) -> str:
    """Перевести символы из QWERTY в ЙЦУКЕН (посимвольно)."""
    if not text:
        return ""
    return "".join(_LAYOUT_MAP.get(ch, ch) for ch in text)


def _looks_russian_medical(text: str) -> bool:
    low = text.lower().replace("ё", "е")
    tokens = _RU_TOKEN.findall(low)
    for tok in tokens:
        for stem in _RU_MED_STEMS:
            if stem in tok:
                return True
    return False


def maybe_fix_layout(text: str | None) -> tuple[str, bool]:
    """Вернуть (исправленный_текст, было_ли_исправление).

    Исправляем, только если в тексте нет кириллицы и конвертация даёт русский
    клинический запрос (совпала хотя бы одна медицинская основа слова).
    """
    src = (text or "").strip()
    if not src or has_cyrillic(src):
        return src, False
    converted = fix_keyboard_layout(src)
    if converted == src:
        return src, False
    if _looks_russian_medical(converted):
        return converted, True
    return src, False
