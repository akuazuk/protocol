def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", (s or "").lower().replace("ё", "е")).strip()


def main() -> int:
    exams: dict[str, set[str]] = {k: set(_norm(v) for v in vs) for k, vs in EXAMS_SEED.items()}
    drugs: dict[str, set[str]] = {k: set(_norm(v) for v in vs) for k, vs in DRUG_GROUPS_SEED.items()}

    # Агрегация из протоколов: названия обследований + aliases, группы препаратов.
    proto_exams = 0
    proto_drugs = 0
    for fp in sorted(JSON_DIR.glob("*.json")):
        try:
            j = json.loads(fp.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        for cond in j.get("conditions") or []:
            if not isinstance(cond, dict):
                continue
            for ex in (cond.get("required_exams") or []) + (cond.get("conditional_exams") or []):
                if not isinstance(ex, dict) or not ex.get("name"):
                    continue
                name = _norm(ex["name"])
                if len(name) < 4:
                    continue
                exams.setdefault(name, set())
                for al in ex.get("aliases") or []:
                    a = _norm(al)
                    if a and a != name:
                        exams[name].add(a)
                        proto_exams += 1
            tr = cond.get("treatment") or {}
            if isinstance(tr, dict):
                for g in tr.get("drug_groups") or []:
                    if isinstance(g, dict) and g.get("drug_group"):
                        gn = _norm(g["drug_group"])
                        if len(gn) >= 4:
                            drugs.setdefault(gn, set())
                            proto_drugs += 1

    out = {
        "version": "1.0",
        "generated_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
        "note_ru": "Синонимы обследований/препаратов: аббревиатуры КЗ ↔ полные названия протоколов. Для семантического матча (Э2).",
        # Только записи с ≥1 вариантом: словарь синонимов, а не список названий.
        # Канон без вариантов не помогает матчу и затеняет курируемые записи.
        "exams": {k: sorted(v) for k, v in sorted(exams.items()) if v},
        "drug_groups": {k: sorted(v) for k, v in sorted(drugs.items()) if v},
        "counts": {
            "exams": sum(1 for v in exams.values() if v),
            "drug_groups": sum(1 for v in drugs.values() if v),
            "seed_exams": len(EXAMS_SEED),
            "seed_drug_groups": len(DRUG_GROUPS_SEED),
        },
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")

    # Мини-тест recall на типичных сокращениях КЗ (цель ≥ 0.85).
    tests = [
        ("оак", "общий анализ крови"), ("узи обп", "ультразвуковое исследование органов брюшной полости"),
        ("фгдс", "эзофагогастродуоденоскопия"), ("экг", "электрокардиография"),
        ("бак", "биохимический анализ крови"), ("мрт", "магнитно-резонансная томография"),
        ("кт", "компьютерная томография"), ("ттг", "тиреотропный гормон"),
        ("пса", "простатический специфический антиген"), ("ипп", "ингибиторы протонной помпы"),
        ("нпвс", "нестероидные противовоспалительные средства"), ("холтер", "холтеровское мониторирование"),
        ("энмг", "электронейромиография"), ("фвд", "исследование функции внешнего дыхания"),
        ("уздг", "ультразвуковая допплерография"), ("соэ", "скорость оседания эритроцитов"),
    ]
    def resolve(term: str) -> str | None:
        t = _norm(term)
        for canon, vs in {**exams, **drugs}.items():
            if t == canon or t in vs:
                return canon
        return None
    hits = sum(1 for term, exp in tests if resolve(term) == exp)
    recall = hits / len(tests)

    n_ex = sum(1 for v in exams.values() if v)
    n_dr = sum(1 for v in drugs.values() if v)
    print(f"exams_with_variants={n_ex} drug_groups_with_variants={n_dr} "
          f"(отброшено безвариантных: {len(exams) - n_ex} exam; proto aliases +{proto_exams})")
    print(f"recall на тесте сокращений: {hits}/{len(tests)} = {recall:.2f} (цель ≥ 0.85)")
    print(f"-> {OUT}")
    return 0


